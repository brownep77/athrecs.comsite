type ProfileArgs = {
  slug: string;
  displayName: string;
  givenName: string;
  familyName: string;
  gender: "M" | "F";
  city: string;
  county: string;
  country: string;
  nationality: string;
  nation: string;
  continent: string;
  commonwealth?: boolean;
  bio: string;
  roles: string[];
  source: string;
  sourceLabel: string;
  athrecsId: string;
  achievement: {
    year: number;
    title: string;
    detail: string;
  };
  links?: Array<{ label: string; url: string }>;
};

function profile(args: ProfileArgs): AthleteSeed {
  return {
    slug: args.slug,
    display_name: args.displayName,
    given_name: args.givenName,
    family_name: args.familyName,
    gender: args.gender,
    club_slug: "unattached",
    source_club_name: "Unattached",
    city: args.city,
    county: args.county,
    country: args.country,
    nationality: args.nationality,
    nation: args.nation,
    continent: args.continent,
    commonwealth: args.commonwealth,
    bio: args.bio,
    race_entry_name: args.displayName,
    preferred_distance: args.bio.includes("IRONMAN") ? "Triathlon" : "Marathon",
    athrecs_id: args.athrecsId,
    notes: "Only publicly reported, source-matched race results are published on this profile.",
    source_url: args.source,
    profile_type: "Public figure",
    profile_roles: args.roles,
    profile_source_checked_at: CHECKED_AT,
    profile_links: [{ label: args.sourceLabel, url: args.source }, ...(args.links ?? [])],
    notable_achievements: [
      {
        ...args.achievement,
        source_url: args.source,
      },
    ],
  };
}

