function verifiedEntry(
  providerCode: string,
  providerName: string,
  entryUrl: string,
  status: EntryOptionStatus = "open",
  priceAmount?: number,
  priceCurrency?: "EUR" | "GBP",
  notes = "Official organiser, governing-body or direct registration page.",
): EntryOptionSeed[] {
  return [
    {
      providerCode,
      providerName,
      entryUrl,
      entryType: "official",
      status,
      ...(priceAmount !== undefined ? { priceAmount } : {}),
      ...(priceCurrency ? { priceCurrency } : {}),
      checkedAt: CHECKED_AT,
      sourceUrl: entryUrl,
      isVerified: true,
      isPrimary: true,
      notes,
    },
  ];
}

