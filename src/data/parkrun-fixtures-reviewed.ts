const rules = new Map(facts.rules.map((rule) => [rule.slug, rule]));
const occurrenceKey = (slug: string, date: string, distance: string) =>
  `${slug}|${date}|${distance}`;
const specialKeys = new Set(
  facts.special.map((row) => occurrenceKey(row.slug, row.date, row.distance)),
);
const cancellations = new Map(
  facts.cancellations.map((row) => [occurrenceKey(row.slug, row.date, row.distance), row]),
);

export function reviewParkrunEdition(edition: Edition): Edition {
  if (edition.date < facts.fromDate || edition.date > facts.toDate) return edition;
  const rule = rules.get(edition.seriesSlug);
  const cancellation = cancellations.get(
    occurrenceKey(edition.seriesSlug, edition.date, edition.distance),
  );
  let reviewed = edition;
  if (rule?.startTime && rule.distance === edition.distance) {
    reviewed = {
      ...reviewed,
      startTime: rule.startTime,
      entryUrl:
        !edition.entryUrl || edition.entryUrl === rule.oldSource ? rule.source : edition.entryUrl,
      source:
        edition.status === "Cancelled" ||
        specialKeys.has(occurrenceKey(edition.seriesSlug, edition.date, edition.distance))
          ? edition.source
          : rule.source,
      entryOptions: edition.entryOptions?.map((option) =>
        option.entryUrl === rule.oldSource ? { ...option, entryUrl: rule.source } : option,
      ),
    };
  }
  if (rule?.closed || cancellation) {
    reviewed = {
      ...reviewed,
      status: "Cancelled",
      source: cancellation?.source ?? rule!.source,
      notes: cancellation
        ? `Official cancellation: ${cancellation.reason}. Checked 10 October 2026.`
        : "The official venue page says this event no longer takes place. Checked 10 October 2026.",
      entryOptions: reviewed.entryOptions?.map((option) => ({ ...option, status: "closed" })),
    };
  }
  return reviewed;
}

export const reviewedParkrunEditions: Edition[] = (() => {
  const rows = new Map<string, Edition>();
  for (const rule of facts.rules) {
    if (rule.closed || !rule.startTime || !rule.weekday) continue;
    const first =
      rule.firstDate && rule.firstDate > facts.fromDate ? rule.firstDate : facts.fromDate;
    const weekday = rule.weekday === "Saturday" ? 6 : 0;
    for (
      const day = new Date(`${first}T12:00:00Z`);
      day.toISOString().slice(0, 10) <= facts.toDate;
      day.setUTCDate(day.getUTCDate() + 1)
    ) {
      if (day.getUTCDay() !== weekday) continue;
      const date = day.toISOString().slice(0, 10);
      const edition: Edition = {
        seriesSlug: rule.slug,
        date,
        distance: rule.distance,
        distanceKm: rule.km,
        status: "Open",
        startTime: rule.startTime,
        source: rule.source,
        entryUrl: rule.source,
        notes: `Regular weekly parkrun schedule: ${rule.weekday} at ${rule.startTime} local time. Subject to cancellation; check the official event page. Schedule checked ${rule.checkedAt.slice(0, 10)}.`,
      };
      rows.set(occurrenceKey(rule.slug, date, rule.distance), reviewParkrunEdition(edition));
    }
  }
  for (const row of facts.special) {
    const edition: Edition = {
      seriesSlug: row.slug,
      date: row.date,
      distance: row.distance,
      distanceKm: row.distanceKm,
      status: "Open",
      startTime: row.startTime ?? undefined,
      source: row.source,
      entryUrl: row.url,
      notes:
        "Additional parkrun day confirmed on the official Christmas/New Year declaration list, checked 10 October 2026. " +
        (row.startTime
          ? "Uses the venue’s published local start time."
          : "Local start time awaiting individual venue verification."),
    };
    rows.set(occurrenceKey(row.slug, row.date, row.distance), edition);
  }
  return [...rows.values()];
})();
