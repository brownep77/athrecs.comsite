function entryOptionsFor(seed: FiveKSeed, seedDate: SeedDate): EntryOptionSeed[] | undefined {
  const status = seedDate.status ?? "Open";
  const hasEntry = seedDate.hasEntry ?? status !== "TBC";
  if (!hasEntry) return undefined;

  const entryUrl = seedDate.url ?? seed.url;
  const entryStatus =
    seedDate.entryStatus ??
    (status === "Closed" ? "closed" : status === "TBC" ? "unknown" : "open");
  return [
    {
      providerCode: `official-${seed.slug}`,
      providerName: seedDate.providerName ?? seed.organiser,
      entryUrl,
      entryType: seedDate.entryType ?? "official",
      status: entryStatus,
      ...(seedDate.priceAmount ? { priceAmount: seedDate.priceAmount, priceCurrency: "GBP" } : {}),
      checkedAt: CHECKED_AT,
      sourceUrl: entryUrl,
      isVerified: true,
      isPrimary: true,
      notes:
        seedDate.notes ??
        (seedDate.entryType === "third_party"
          ? "Direct event listing on the named registration provider."
          : "Official organiser or event entry page."),
    },
  ];
}

