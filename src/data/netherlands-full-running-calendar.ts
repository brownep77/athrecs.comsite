function entryOption(config: RaceConfig, entryUrl: string): EntryOptionSeed {
  return {
    providerCode: config.slug,
    providerName: config.organiser,
    entryUrl,
    entryType: "official",
    status: "unknown",
    checkedAt: CHECKED_AT,
    sourceUrl: entryUrl,
    isVerified: true,
    isPrimary: true,
  };
}

export const netherlandsFullRaceEditions: Edition[] = raceConfigs.flatMap((config) =>
  config.occurrences.flatMap((occurrence) =>
    occurrence.distances.map((distance) => {
      const entryUrl = distance.entryUrl ?? occurrence.entryUrl;
      const source = distance.source ?? occurrence.source;
      return {
        seriesSlug: config.slug,
        date: occurrence.date,
        distance: distance.label,
        distanceKm: distance.km,
        status: occurrence.status,
        ...(occurrence.status === "Open" && entryUrl
          ? { entryUrl, entryOptions: [entryOption(config, entryUrl)] }
          : {}),
        ...(distance.time ? { startTime: distance.time } : {}),
        source,
        notes: `Organiser-owned or organiser-authorised date and distance evidence checked on ${CHECKED_AT}.`,
        publishAllDistances: true,
      } satisfies Edition;
    }),
  ),
);
