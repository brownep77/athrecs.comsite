function entryOptionsFor(seed: FiveKSeed): EntryOptionSeed[] | undefined {
  const status = seed.status ?? "Open";
  const hasEntry = seed.hasEntry ?? status !== "TBC";
  if (!hasEntry) return undefined;

  return [
    {
      providerCode: `official-${seed.slug}`,
      providerName: seed.organiser,
      entryUrl: seed.url,
      entryType: "official",
      status: seed.entryStatus ?? (status === "Closed" ? "closed" : "open"),
      checkedAt: CHECKED_AT,
      sourceUrl: seed.url,
      isVerified: true,
      isPrimary: true,
      notes: "Official organiser or direct event-registration page.",
    },
  ];
}

