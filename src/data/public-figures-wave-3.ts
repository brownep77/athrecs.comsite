type ResultArgs = {
  athleteSlug: string;
  eventSlug?: string;
  date: string;
  time: string;
  category: "Men" | "Women";
  source: string;
  resultSource: string;
};

function finishTimeSeconds(time: string) {
  const [hours, minutes, seconds] = time.split(":").map(Number);
  return hours * 3600 + minutes * 60 + seconds;
}

function marathonResult(args: ResultArgs): ResultSeed {
  return {
    eventSlug: args.eventSlug ?? "london-marathon",
    date: args.date,
    distance: "Marathon",
    athleteSlug: args.athleteSlug,
    place: null,
    time: args.time,
    finishTimeSeconds: finishTimeSeconds(args.time),
    status: "finished",
    category: args.category,
    resultSource: args.resultSource,
    source: args.source,
  };
}

