function entryOptionsFor(seed: ProminentRaceSeed): EntryOptionSeed[] | undefined {
  if (!seed.entryUrl) return undefined;
  const entryStatus =
    seed.entryStatus ??
    (seed.status === "Closed" ? "closed" : seed.status === "TBC" ? "unknown" : "open");
  return [
    {
      providerCode: `official-${seed.slug}`,
      providerName: seed.organiser,
      entryUrl: seed.entryUrl,
      entryType: "official",
      status: entryStatus,
      checkedAt: CHECKED_AT,
      sourceUrl: seed.sourceUrl,
      isVerified: true,
      isPrimary: true,
      notes: "Official organiser, governing-body fixture or official entry-information page.",
    },
  ];
}

