function entryOptionsFor(seed: NonStandardSeed): EntryOptionSeed[] | undefined {
  if (seed.hasEntry === false || seed.status === "TBC") return undefined;
  return [
    {
      providerCode: `official-${seed.slug}`,
      providerName: seed.organiser,
      entryUrl: seed.url,
      entryType: "official",
      status: seed.status === "Closed" ? "closed" : "open",
      checkedAt: NON_STANDARD_DISTANCE_CHECKED_AT,
      sourceUrl: seed.url,
      isVerified: true,
      isPrimary: true,
      notes: "Official organiser, registration-provider or governing-body listing.",
    },
  ];
}

