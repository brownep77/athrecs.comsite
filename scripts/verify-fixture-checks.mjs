import assert from "node:assert/strict";
import { checkRows } from "./source-importer/checks.mjs";
const base = { name: "Town 10K", country: "England", city: "Leeds", date: "2027-03-14", distance: "10", unit: "km", startTime: "10:00", sourceUrl: "https://example.org/race", sourceKind: "organiser", evidence: "Event page gives Sunday 14 March 2027 for the 10K", checkedAt: "2026-10-26", entryStatus: "Open" };
const run = (o, extra = []) => checkRows([{ ...base, ...o }, ...extra], { today: "2026-10-26" });
const has = (f, check, sev) => f.some((x) => x.check === check && (!sev || x.severity === sev));
assert.equal(run({}).filter((f) => f.severity !== "info").length, 0, "clean row has no warnings");
assert.ok(has(run({ date: "2026-10-01" }), "date", "error"), "past date");
assert.ok(has(run({ date: "2027-02-30" }), "date", "error"), "impossible date");
assert.ok(has(run({ startTime: "25:00" }), "time", "error"), "bad time");
assert.ok(has(run({ startTime: "03:00" }), "time", "warn"), "early start");
assert.ok(has(run({ distance: "5" }), "distance", "warn"), "name says 10K, distance 5");
assert.ok(!has(run({ name: "Pudding Run 5K & 10K", distance: "5" }), "distance", "warn"), "two-distance name ok");
assert.ok(has(run({ city: "Kent" }), "place", "warn"), "county as city");
assert.ok(has(run({ city: "Anywhere" }), "place", "error"), "non-place city");
assert.ok(has(run({ sourceUrl: "https://www.runabc.com/x" }), "source", "error"), "discovery calendar");
assert.ok(has(run({ sourceUrl: "https://example.org/results/2026" }), "source", "error"), "results page");
assert.ok(has(run({ entryStatus: "Sold out" }), "entry", "error"), "bad entry status");
assert.ok(has(run({}, [{ ...base, name: "Town 5K", distance: "5" }]), "name", "warn"), "distance-specific names for one event");
assert.ok(has(run({ date: "2027-03-17" }), "date", "warn"), "weekday daytime start");
assert.ok(!has(run({ date: "2027-01-01", name: "New Year 10K" }), "date", "warn"), "holiday weekday ok");
assert.ok(has(run({}, [{ ...base, city: "York" }]), "conflict", "warn"), "same event different towns");
console.log("fixture checks ok");
