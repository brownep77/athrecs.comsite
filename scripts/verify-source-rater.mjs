import assert from "node:assert/strict";
import { candidates, distLabel, groupRows, judge, parsePage, rateSources } from "./source-importer/rate.mjs";
assert.equal(distLabel({ distance: "42.195", unit: "km" }), "marathon");
assert.equal(distLabel({ distance: "13.1", unit: "mi" }), "half");
assert.equal(distLabel({ distance: "10", unit: "mi" }), "10mi");
const page = parsePage('<p>Half · 21.1 km 2027-02-28 · 09:00</p><p>Naas · Kildare</p><p>10mi · 16.09 km</p>'.replace("10mi", "x · 10mi"));
const slugs = ["wymondham-nyd-10k", "naas-parkrun", "naas-10-mile-half-marathon-2027", "other-race"];
assert.ok(candidates("Naas 10 Mile & Half Marathon 2027", slugs).includes("naas-10-mile-half-marathon-2027"));
assert.ok(candidates("Wymondham New Year's Day 10k", slugs, 12, "Wymondham").includes("wymondham-nyd-10k"), "town match finds abbreviated slugs");
const mk = (dates, dist, text = "naas") => ({ slug: "s", page: { dates: new Set(dates), distances: new Set(dist), text } });
const g = { date: "2027-02-28", city: "Naas", distances: ["half", "10mi"] };
assert.equal(judge(g, [mk(["2027-02-28"], ["half", "10mi"])]).verdict, "confirmed");
assert.equal(judge(g, [mk(["2027-02-28"], ["half"])]).verdict, "distance-missing");
assert.equal(judge(g, [mk(["2027-02-28"], [], "naas")]).verdict, "unverified");
assert.equal(judge(g, [mk(["2027-03-06"], ["half"])]).verdict, "date-conflict");
assert.equal(judge(g, [mk(["2026-02-28"], ["half"])]).verdict, "other-edition");
assert.equal(judge(g, []).verdict, "not-on-site");
assert.equal(judge(g, [mk(["2027-02-28"], ["half", "10mi"], "elsewhere")]).verdict, "town-differs");
const rows = [{ name: "A 5K", date: "2027-01-01", city: "X", distance: "5", unit: "km", sourceUrl: "https://www.example.org/a" }, { name: "A 5K", date: "2027-01-01", city: "X", distance: "10", unit: "km", sourceUrl: "https://www.example.org/a" }];
assert.equal(groupRows(rows).length, 1);
assert.deepEqual(groupRows(rows)[0].distances, ["5k", "10k"]);
const rated = rateSources([{ host: "a.org", verdict: "confirmed" }, { host: "a.org", verdict: "confirmed" }, { host: "a.org", verdict: "date-conflict" }, { host: "b.org", verdict: "not-on-site" }]);
assert.equal(rated.find((r) => r.host === "a.org").compared, 3);
assert.match(rated.find((r) => r.host === "b.org").rating, /Unrated/);
